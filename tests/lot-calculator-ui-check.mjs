import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs';
const require = createRequire(process.env.DAYRIS_PLAYWRIGHT_PACKAGE || 'C:/Users/aveel/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json');
const bundle = await createRequire(path.resolve('package.json'))('esbuild').build({entryPoints:[path.resolve('tests/workspace-panel-ui.jsx')],bundle:true,write:false,outfile:'workspace.js',format:'iife',define:{'process.env.NODE_ENV':'"production"'}});
const js=bundle.outputFiles.find(file=>file.path.endsWith('.js')).text, css=bundle.outputFiles.find(file=>file.path.endsWith('.css')).text;
const browser=await require('playwright').chromium.launch({channel:'msedge',headless:true});
try {
  const page=await browser.newPage({viewport:{width:390,height:844}}), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('http://dayris.test/**',route=>route.fulfill({contentType:'text/html',body:`<!doctype html><html><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}</style><div id="root"></div><script>${js}</script></html>`}));
  await page.goto('http://dayris.test/');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('#idle').click();
  assert.equal(await page.getByRole('button',{name:'Калькулятор лота',exact:true}).count(),0);
  await page.locator('#trader').click();
  await page.getByRole('button',{name:'Калькулятор лота',exact:true}).click();
  assert.ok(await page.getByRole('dialog').isVisible());
  await page.getByLabel('Баланс счёта',{exact:true}).fill('10000');
  await page.getByLabel('Стоп-лосс, пипсов / тиков',{exact:true}).fill('20');
  await page.getByLabel('Цена пипса / тика за 1 лот, USD',{exact:true}).fill('10');
  assert.match(await page.locator('[data-lot-result]').innerText(),/0,5/);
  assert.equal(await page.locator('[data-lot-loss]').innerText(),'100 USD');
  await page.getByLabel('Стоп-лосс, пипсов / тиков',{exact:true}).fill('0');
  assert.equal(await page.locator('[data-lot-result]').count(),0,'Invalid inputs clear the old result');
  await page.getByLabel('Стоп-лосс, пипсов / тиков',{exact:true}).fill('20');
  await page.getByLabel('Баланс счёта',{exact:true}).fill('10');
  assert.match(await page.locator('.lot-result').innerText(),/Минимальный лот превышает/);
  await page.getByLabel('Баланс счёта',{exact:true}).fill('10000');
  await page.getByLabel('Валюта счёта',{exact:true}).selectOption('EUR');
  assert.equal(await page.getByLabel('Баланс счёта',{exact:true}).inputValue(),'');
  assert.equal(await page.getByLabel('Цена пипса / тика за 1 лот, EUR',{exact:true}).inputValue(),'');
  await page.getByLabel('Баланс счёта',{exact:true}).fill('10000');
  await page.getByLabel('Цена пипса / тика за 1 лот, EUR',{exact:true}).fill('10');
  await page.locator('summary').click();
  await page.getByLabel('Комиссия за 1 лот, EUR',{exact:true}).fill('7');
  assert.match(await page.locator('[data-lot-result]').innerText(),/0,48/);
  for(const width of [320,390,1280]) {
    await page.setViewportSize({width,height:844});
    const bounds=await page.getByRole('dialog').boundingBox();
    assert.ok(bounds.x>=0 && bounds.x+bounds.width<=width && bounds.height<=812);
    assert.equal(await page.getByRole('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  }
  await page.screenshot({path:'tests/lot-calculator-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'tests/lot-calculator-mobile.png'});
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  assert.equal(await page.getByRole('button',{name:'Калькулятор лота',exact:true}).evaluate(el=>el===document.activeElement),true);
  await page.locator('#theme').click();
  await page.getByRole('button',{name:'Калькулятор лота',exact:true}).click();
  assert.equal(await page.getByRole('dialog').getAttribute('data-light'),'true');
  await page.getByRole('button',{name:'Закрыть калькулятор'}).click();
  await page.locator('#idle').click();
  assert.equal(await page.getByRole('button',{name:'Калькулятор лота',exact:true}).count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS: trader-only calculator, lot and fee results, currency reset, validation, responsive dialog, Escape and focus return.');
} finally { await browser.close(); }
