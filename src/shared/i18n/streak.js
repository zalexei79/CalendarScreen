export function streakDayLabel(days, language) {
  if (String(language).toLowerCase().startsWith('zh')) return `${days} 天`;
  if (language === 'en') return `${days} ${days === 1 ? 'day' : 'days'}`;
  if (language === 'md' || language === 'ro') return `${days} ${days === 1 ? 'zi' : 'zile'}`;
  const plural = new Intl.PluralRules(language === 'uk' ? 'uk' : 'ru').select(days);
  const words = language === 'uk' ? { one: 'день', few: 'дні', many: 'днів', other: 'дня' }
    : { one: 'день', few: 'дня', many: 'дней', other: 'дня' };
  return `${days} ${words[plural]}`;
}
