export function plannerLanguage(language) {
  const code = String(language || '').toLowerCase();
  if (code === 'en' || code.startsWith('en-')) return 'en';
  if (code === 'md' || code === 'ro' || code.startsWith('ro-')) return 'ro';
  return 'ru';
}

